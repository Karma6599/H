function entryKind(index) {
  return PROFILE_MASK.charAt(index) === '1' ? NUMBER_ENTRY : STRING_ENTRY;
}

function numberIndexes() {
  const out = [];
  for (let i = 0; i < PROFILE_SIZE; i++) {
    if (PROFILE_MASK.charAt(i) === '1') out.push(i);
  }
  return out;
}

function stringIndexes() {
  const out = [];
  for (let i = 0; i < PROFILE_SIZE; i++) {
    if (PROFILE_MASK.charAt(i) === '0') out.push(i);
  }
  return out;
}

function validateNumber(value) {
  if (typeof value !== 'number' || !isFinite(value) ||
      Math.abs(value) > MAX_OFFSET_VALUE) {
    throw new Error('Invalid offset value: ' + value);
  }
  return value;
}

function validateConstant(value) {
  if (typeof value !== 'string' || value.length > MAX_CONSTANT_LENGTH ||
      !NATIVE_CONSTANT_PATTERN.test(value)) {
    throw new Error('Invalid native constant: ' + value);
  }
  return value;
}

function validateProfile(values) {
  if (!Array.isArray(values) || values.length !== PROFILE_SIZE) {
    throw new Error('Incompatible offset profile: ' +
      (values ? values.length : 'missing') + ' != ' + PROFILE_SIZE);
  }
  for (let i = 0; i < PROFILE_SIZE; i++) {
    if (PROFILE_MASK.charAt(i) === '1') {
      validateNumber(values[i]);
    } else {
      validateConstant(values[i]);
    }
  }
  return Object.freeze(values.slice());
}

function registrySlotFor(index) {
  for (let i = 0; i < DISTRIBUTION.length; i += 2) {
    if (DISTRIBUTION[i] === index) return DISTRIBUTION[i + 1];
  }
  return -1;
}

function distributionTable() {
  const out = [];
  for (let i = 0; i < DISTRIBUTION.length; i += 2) {
    out.push({ index: DISTRIBUTION[i], registrySlot: DISTRIBUTION[i + 1] });
  }
  return out;
}

function buildFeatureDeps(values) {
  const frozen = Array.isArray(values) ? Object.freeze(values.slice())
    : validateProfile(values);
  return {
    offsetValues: frozen,
    numberCount: numberIndexes().length,
    stringCount: stringIndexes().length,
    menu: {
      first: frozen[180],
      second: frozen[181],
    },
    featureBlock: {
      first: frozen[FEATURE_BLOCK_FIRST],
      last: frozen[FEATURE_BLOCK_LAST],
      size: FEATURE_BLOCK_SIZE,
    },
    registrySlots: distributionTable(),
  };
}

function createOffsetProfile(deps) {
  const state = {
    loaded: false,
    values: null,
    lastError: '',
    disposed: false,
  };

  function load(values) {
    if (state.disposed) {
      throw new Error('Offset profile disposed');
    }
    state.values = validateProfile(values);
    state.loaded = true;
    return state.values;
  }

  function setEnabled(value) {
    return value === true;
  }

  function applySaved(saved) {
    if (saved && Array.isArray(saved.values)) {
      load(saved.values);
    }
  }

  function tick() {}

  function getState() {
    return {
      loaded: state.loaded,
      size: state.values ? state.values.length : 0,
      numbers: state.values ? numberIndexes().length : 0,
      constants: state.values ? stringIndexes().length : 0,
      lastError: state.lastError,
      disposed: state.disposed,
    };
  }

  function dispose() {
    state.values = null;
    state.loaded = false;
    state.disposed = true;
  }

  return {
    load,
    buildFeatureDeps,
    setEnabled,
    applySaved,
    tick,
    getState,
    dispose,
  };
}

